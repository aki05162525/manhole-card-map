"""Generate the coast drawn on the map screen before the basemap is ready.
Usage: python3 tools/map/national_outline.py INPUT.zip web/src/features/map/national-outline.ts

Illustration only, like og_outline.py and by the same method, over every
island of the source. The loops are simplified and written as one SVG path
in Web Mercator, so the page places it with a scale and a translation.
"""
import math
import sys

from generate import simplify
from og_outline import GRID, coast_rings

WINDOW = (120.0, 20.0, 156.0, 46.5)
TOLERANCE = 2500
# The path's origin and unit: degrees of longitude, and the Mercator
# ordinate in the same unit, counted in hundredths from this corner.
WEST = 120.0
NORTH = 46.5
UNIT = 0.01


def mercator(lat):
    return math.degrees(math.log(math.tan(math.pi / 4 + math.radians(lat) / 2)))


def project(lng, lat):
    return round((lng - WEST) / UNIT), round((mercator(NORTH) - mercator(lat)) / UNIT)


def path(rings):
    parts = []
    for points in rings:
        projected = []
        for lng, lat in points:
            point = project(lng, lat)
            if not projected or projected[-1] != point:
                projected.append(point)
        if len(projected) > 1 and projected[0] == projected[-1]:
            projected.pop()
        if len(projected) < 3:
            continue
        x, y = projected[0]
        steps = [f"M{x} {y}"]
        for nx, ny in projected[1:]:
            steps.append(f"l{nx - x} {ny - y}")
            x, y = nx, ny
        parts.append("".join(steps) + "z")
    return "".join(parts)


def main(source, output):
    rings = []
    for loop in sorted(coast_rings(source, WINDOW), key=len, reverse=True):
        points = [(x * GRID, y * GRID) for x, y in loop]
        rings.append(simplify(points + points[:1], TOLERANCE))
    data = path(rings)
    with open(output, "w", encoding="utf-8") as stream:
        stream.write(
            "// Generated by tools/map/national_outline.py; do not edit.\n"
            "// 出典：国土交通省「国土数値情報（行政区域データ）」N03-20260101 を加工して作成\n"
            "/** The path's corner, and the degrees of one of its units. */\n"
            f"export const OUTLINE_ORIGIN = {{ west: {WEST}, north: {NORTH}, unit: {UNIT} }};\n"
            "/** Japan's coast in Web Mercator. Illustration only. */\n"
            f'export const NATIONAL_OUTLINE =\n  "{data}";\n'
        )
    print(f"rings={len(rings)} points={sum(len(r) for r in rings)} bytes={len(data)}")


if __name__ == "__main__":
    main(*sys.argv[1:])
